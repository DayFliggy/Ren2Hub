param(
    [string]$Baseline = 'a2d7371b2bf0a3ee50e7a69b895caa08730460b6',
    [string]$RedisAddress = '127.0.0.1:16379'
)
$ErrorActionPreference = 'Stop'
$project = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$runDirectory = Join-Path $project ('.local-tests/admission-comparison/' + [Guid]::NewGuid().ToString('N'))
$utf8 = New-Object System.Text.UTF8Encoding($false)
New-Item -ItemType Directory -Path $runDirectory -Force | Out-Null
$previousRedisAddress = $env:ADMISSION_BENCHMARK_REDIS_ADDR
Push-Location $project
try {
    $revision = & git rev-parse --verify "$Baseline^{commit}"
    if ($LASTEXITCODE -ne 0) { throw 'Baseline must resolve to an existing local commit.' }
    foreach ($name in @('route_lease.go', 'route_lease_queue.go')) {
        $source = & git show "${revision}:service/$name"
        if ($LASTEXITCODE -ne 0) { throw "Baseline is missing service/$name" }
        $source = ($source -join "`n") -replace '^package service', 'package main'
        [IO.File]::WriteAllText((Join-Path $runDirectory $name), $source, $utf8)
    }
    Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'main.go.template') -Destination (Join-Path $runDirectory 'main.go')
    $env:ADMISSION_BENCHMARK_REDIS_ADDR = $RedisAddress
    $results = & go run $runDirectory
    if ($LASTEXITCODE -ne 0) { throw 'Admission comparison failed.' }
    [IO.File]::WriteAllText((Join-Path $runDirectory 'results.json'), ($results -join "`n"), $utf8)
    [IO.File]::WriteAllText((Join-Path $runDirectory 'baseline.txt'), $revision, $utf8)
    Write-Output (Join-Path $runDirectory 'results.json')
} finally {
    $env:ADMISSION_BENCHMARK_REDIS_ADDR = $previousRedisAddress
    Pop-Location
    # Only the three source files generated by this invocation are temporary.
    foreach ($name in @('route_lease.go', 'route_lease_queue.go', 'main.go')) {
        $target = Join-Path $runDirectory $name
        if (Test-Path -LiteralPath $target) { Remove-Item -LiteralPath $target }
    }
}
